#!/usr/bin/env node
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { pngToFramebuffer, FRAME_BYTES } from '../src/pack.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const png = await readFile(path.join(root, 'design/exports/states/state-setup.png'));
const flags = JSON.parse(await readFile(path.join(root, 'server/config.json'), 'utf8'));
const frame = pngToFramebuffer(png, flags);
const rows = [];
for (let offset = 0; offset < frame.length; offset += 16) {
  rows.push(`  ${Array.from(frame.subarray(offset, offset + 16), value => `0x${value.toString(16).padStart(2, '0')}`).join(', ')},`);
}
const header = `// Generated by server/bin/pack-setup.js from design/exports/states/state-setup.png.\n` +
  `// Wire format: ${flags.whiteIsOne ? '1=white' : '1=black'}, ${flags.msbFirst ? 'MSB' : 'LSB'} first.\n` +
  `#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n` +
  `const uint8_t setup_frame[${FRAME_BYTES}] PROGMEM = {\n${rows.join('\n')}\n};\n` +
  `const uint32_t setup_frame_len = sizeof(setup_frame);\n`;
const destination = path.join(root, 'firmware/assets/setup_frame.h');
await mkdir(path.dirname(destination), { recursive: true });
await writeFile(destination, header);
console.log(`Wrote ${destination} (${frame.length} framebuffer bytes)`);
